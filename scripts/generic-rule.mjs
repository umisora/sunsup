function namesPrefecture(name) {
  return PREFECTURES.some((prefecture) => name.includes(prefecture));
}

/** 品名だけで判定する。リンクや紹介文は見ない。 */
export function isGenericProduct(name) {
  if ((/野菜生活/.test(name) || /^カゴメ/.test(name)) && namesPrefecture(name)) {
    return false;
  }
  return LINES.some((line) => line.test(name));
}
