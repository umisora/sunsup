// Writes public/_routes.json and lib/season-slugs.ts.
//
// Functions run on every page so functions/_middleware.ts can send the old production host
// (sunsup-dv4.pages.dev) to stylish.sunsup.me. Static folders stay excluded, so images, fonts and
// scripts never invoke a function. The season function only rewrites the drink pages listed in
// lib/season-slugs.ts (from data/still-seasons.json); every other page passes through untouched.
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const manifest = JSON.parse(readFileSync(join("data", "still-seasons.json"), "utf8"));
const slugs = Object.keys(manifest.drinks).sort();

export const STATIC_EXCLUDES = [
  "/_next/*",
  "/brand/*",
  "/fonts/*",
  "/drinks/*",
  "/images/*",
  "/og/*",
  "/icon.png",
  "/icon-192.png",
  "/icon-512.png",
  "/manifest.webmanifest",
];

const routes = { version: 1, include: ["/*"], exclude: STATIC_EXCLUDES };
writeFileSync(join("public", "_routes.json"), `${JSON.stringify(routes, null, 2)}\n`);
writeFileSync(
  join("lib", "season-slugs.ts"),
  `// Generated by scripts/build-season-routes.mjs from data/still-seasons.json. Do not edit.\n` +
    `export const SEASON_SLUGS: ReadonlySet<string> = new Set(${JSON.stringify(slugs)});\n`,
);
console.log(`[season-routes] functions on pages, ${STATIC_EXCLUDES.length} static folders excluded, ${slugs.length} season drink pages`);
